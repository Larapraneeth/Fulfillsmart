"""
FulfillSmart Common API Schemas
Defines standardized API response envelopes and genuine RFC 7807 Problem Details schemas.
"""
from typing import Generic, TypeVar, Optional, Any, List, Dict
from datetime import datetime, timezone
from pydantic import BaseModel, Field

T = TypeVar("T")


class ApiResponseEnvelope(BaseModel, Generic[T]):
    """Standardized API response wrapper for successful operations."""
    status: str = Field(default="success", description="Status string: 'success'")
    data: T = Field(description="Payload data")
    request_id: Optional[str] = Field(default=None, description="Unique request tracing ID")
    process_time_ms: Optional[float] = Field(default=None, description="Execution time in milliseconds")


class RFC7807ProblemDetails(BaseModel):
    """
    Genuine RFC 7807 Problem Details schema (Content-Type: application/problem+json).
    Provides machine-readable error details for HTTP APIs.
    """
    type: str = Field(
        default="about:blank",
        description="A URI reference that identifies the problem type"
    )
    title: str = Field(
        description="A short, human-readable summary of the problem type"
    )
    status: int = Field(
        description="The HTTP status code generated by the origin server"
    )
    detail: str = Field(
        description="A human-readable explanation specific to this occurrence of the problem"
    )
    instance: Optional[str] = Field(
        default=None,
        description="A URI reference that identifies the specific occurrence of the problem"
    )
    error_code: str = Field(
        description="FulfillSmart domain-specific error code"
    )
    invalid_params: Optional[List[Dict[str, Any]]] = Field(
        default=None,
        description="List of invalid parameter details for validation errors"
    )
    request_id: Optional[str] = Field(
        default=None,
        description="Tracing identifier for the failed request"
    )
    timestamp: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="ISO 8601 UTC timestamp of error occurrence"
    )
